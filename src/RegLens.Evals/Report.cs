using System.Globalization;
using System.Text;
using System.Text.Json;

namespace RegLens.Evals;

/// <summary>A row added by hand to an answer run's table, such as the judge hand check (spec 0004, A6).</summary>
public sealed record HandCheck(DateTimeOffset AnswerRunStartedUtc, string Metric, string Value);

/// <summary>Raw run files and the generated <c>evals/results.md</c> (spec 0004, R4.12, P10; spec 0005, R5.15, P9).</summary>
public static class Report
{
    public const string RunsDirectory = "evals/runs";
    public const string ResultsFile = "evals/results.md";
    public const string HandChecksFile = "evals/hand-checks.json";

    /// <summary>Runs saved before spec 0005 recorded no pipeline; they were all built this way.</summary>
    public const string Spec0004Pipeline = "chunker 1; no context";

    /// <summary>The configuration compared question by question across stages: the default (D49).</summary>
    public const string ComparedConfig = "hybrid-bm25";

    public static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web) { WriteIndented = true };

    public static string Save<T>(T run, RunInfo info)
    {
        ArgumentNullException.ThrowIfNull(info);
        Directory.CreateDirectory(RunsDirectory);
        var path = Path.Combine(RunsDirectory,
            string.Create(CultureInfo.InvariantCulture, $"{info.StartedUtc:yyyyMMdd'T'HHmmss'Z'}-{info.Kind}-{info.Config}.json"));
        File.WriteAllText(path, JsonSerializer.Serialize(run, Json));
        return path;
    }

    public static IReadOnlyList<T> Load<T>(string kind) where T : class =>
        [.. Directory.Exists(RunsDirectory)
            ? Directory.GetFiles(RunsDirectory, $"*-{kind}-*.json").Order(StringComparer.Ordinal)
                .Select(path => JsonSerializer.Deserialize<T>(File.ReadAllText(path), Json)!)
            : []];

    public static string Stage(RunInfo info)
    {
        ArgumentNullException.ThrowIfNull(info);
        return info.Pipeline ?? Spec0004Pipeline;
    }

    /// <summary>Latest run per pipeline and configuration, stages in the order they were first run.</summary>
    public static string Write()
    {
        var retrieval = Latest(Load<RetrievalRun>("retrieval"), r => r.Info);
        var answers = Latest(Load<AnswerRun>("answers"), r => r.Info);
        var probes = Load<ProbeRun>("probe");
        var handChecks = LoadHandChecks();
        var stages = Stages(retrieval.Select(r => r.Info).Concat(answers.Select(r => r.Info)));

        var b = new StringBuilder();
        b.AppendLine("# RegLens eval results").AppendLine();
        b.AppendLine("Generated by `src/RegLens.Evals` from `evals/runs/*.json` (specs 0004, 0005). Golden set: `evals/golden-set.json`.");
        b.AppendLine("Each table shows the latest run per pipeline and configuration. The pipeline is how the index was built:");
        b.AppendLine("chunker version and chunk context (spec 0005, P6). Never quote a number without its n.").AppendLine();

        b.AppendLine("## Retrieval (no LLM)").AppendLine();
        b.AppendLine("n = answerable questions. A hit is any chunk matching an expected reference; MRR counts ranks beyond 10 as 0.").AppendLine();
        if (stages.Count > 1)
        {
            WriteStageComparison(b, retrieval, stages);
        }

        foreach (var stage in stages)
        {
            var runs = retrieval.Where(r => Stage(r.Info) == stage).ToList();
            if (runs.Count > 0)
            {
                WriteRetrievalStage(b, stage, runs);
            }
        }

        b.AppendLine("## Answers").AppendLine();
        foreach (var run in answers)
        {
            WriteAnswerRun(b, run, handChecks);
        }

        if (answers.Count == 0)
        {
            b.AppendLine("No answer run yet.").AppendLine();
        }

        b.AppendLine("## Injection probe").AppendLine();
        foreach (var probe in probes)
        {
            b.AppendLine(CultureInfo.InvariantCulture, $"- {probe.Info.StartedUtc:yyyy-MM-dd HH:mm} UTC, commit `{probe.Info.Commit}`, pipeline `{Stage(probe.Info)}`: **{(probe.Passed ? "passed" : "FAILED")}** (canary cited: {probe.CanaryCited}, abstained: {probe.Abstained}, ${Metrics.Format(probe.CostUsd, 3)})");
        }

        if (probes.Count == 0)
        {
            b.AppendLine("No probe run yet.");
        }

        File.WriteAllText(ResultsFile, b.ToString());
        return ResultsFile;
    }

    private static void WriteStageComparison(StringBuilder b, List<RetrievalRun> retrieval, List<string> stages)
    {
        b.AppendLine("### Stage comparison (spec 0005, P9)").AppendLine();
        for (var i = 0; i < stages.Count; i++)
        {
            b.AppendLine(CultureInfo.InvariantCulture, $"- Stage {i + 1}: `{stages[i]}`");
        }

        b.AppendLine().Append("| Configuration |")
            .AppendJoin("", stages.Select((_, i) => $" recall@5 s{i + 1} |"))
            .AppendJoin("", stages.Select((_, i) => $" MRR@10 s{i + 1} |")).AppendLine();
        b.Append("|---------------|").AppendJoin("", stages.Select(_ => "---|")).AppendJoin("", stages.Select(_ => "---|")).AppendLine();
        foreach (var config in EvalConfiguration.All.Select(c => c.Name))
        {
            var byStage = stages.Select(s => retrieval.SingleOrDefault(r => r.Info.Config == config && Stage(r.Info) == s)).ToList();
            b.Append(CultureInfo.InvariantCulture, $"| {config} |")
                .AppendJoin("", byStage.Select(r => r is null ? " – |" : $" {Metrics.Format(r.RecallAt5, 2)} |"))
                .AppendJoin("", byStage.Select(r => r is null ? " – |" : $" {Metrics.Format(r.MrrAt10)} |")).AppendLine();
        }

        var compared = stages.Select(s => retrieval.SingleOrDefault(r => r.Info.Config == ComparedConfig && Stage(r.Info) == s)).ToList();
        var first = compared.FirstOrDefault(r => r is not null);
        if (first is not null)
        {
            b.AppendLine().AppendLine(CultureInfo.InvariantCulture, $"First expected rank per question, {ComparedConfig}, by stage (blank = not in the top 20):").AppendLine();
            b.Append("| Question |").AppendJoin("", stages.Select((_, i) => $" s{i + 1} |")).AppendLine();
            b.Append("|----------|").AppendJoin("", stages.Select(_ => "---|")).AppendLine();
            foreach (var id in first.Questions.Select(q => q.Id))
            {
                b.Append(CultureInfo.InvariantCulture, $"| {id} |")
                    .AppendJoin("", compared.Select(r => r is null ? " – |" : $" {r.Questions.SingleOrDefault(q => q.Id == id)?.FirstHitRank} |"))
                    .AppendLine();
            }
        }

        b.AppendLine();
    }

    private static void WriteRetrievalStage(StringBuilder b, string stage, List<RetrievalRun> runs)
    {
        b.AppendLine(CultureInfo.InvariantCulture, $"### Pipeline `{stage}`").AppendLine();
        b.AppendLine("| Configuration | n | recall@5 | recall@8 | MRR@10 | Run (UTC) | Commit | Embeddings |");
        b.AppendLine("|---------------|---|----------|----------|--------|-----------|--------|------------|");
        foreach (var run in runs)
        {
            b.AppendLine(CultureInfo.InvariantCulture, $"| {run.Info.Config} | {run.N} | {Metrics.Format(run.RecallAt5, 2)} | {Metrics.Format(run.RecallAt8, 2)} | {Metrics.Format(run.MrrAt10)} | {run.Info.StartedUtc:yyyy-MM-dd HH:mm} | `{run.Info.Commit}` | {run.Info.EmbeddingModel} |");
        }

        b.AppendLine().AppendLine("First expected rank per question (blank = not in the top 20):").AppendLine();
        b.Append("| Question |").AppendJoin("", runs.Select(r => $" {r.Info.Config} |")).AppendLine();
        b.Append("|----------|").AppendJoin("", runs.Select(_ => "---|")).AppendLine();
        foreach (var id in runs[0].Questions.Select(q => q.Id))
        {
            b.Append(CultureInfo.InvariantCulture, $"| {id} |").AppendJoin("", runs.Select(r => $" {r.Questions.SingleOrDefault(q => q.Id == id)?.FirstHitRank} |")).AppendLine();
        }

        b.AppendLine();
    }

    private static void WriteAnswerRun(StringBuilder b, AnswerRun run, IReadOnlyList<HandCheck> handChecks)
    {
        b.AppendLine(CultureInfo.InvariantCulture, $"Configuration **{run.Info.Config}**, pipeline `{Stage(run.Info)}`, `{run.Model}` effort {run.Effort}, judge `{run.JudgeModel}`, floor {run.SimilarityFloor}, run {run.Info.StartedUtc:yyyy-MM-dd HH:mm} UTC, commit `{run.Info.Commit}`, n = {run.N}.").AppendLine();
        b.AppendLine("| Metric | Value |").AppendLine("|--------|-------|");
        b.AppendLine(CultureInfo.InvariantCulture, $"| Abstained on unanswerable | {run.UnanswerableAbstained}/{GoldenSet.UnanswerableCount} |");
        b.AppendLine(CultureInfo.InvariantCulture, $"| Wrongly abstained on answerable | {run.AnswerableAbstained}/{GoldenSet.AnswerableCount} |");
        b.AppendLine(CultureInfo.InvariantCulture, $"| Answered and cited an expected paragraph | {run.AnsweredCitingExpected}/{run.AnsweredAnswerable} |");
        b.AppendLine(CultureInfo.InvariantCulture, $"| Citations dropped by the verifier | {run.CitationsDropped} |");
        b.AppendLine(CultureInfo.InvariantCulture, $"| Groundedness, mean 1–5 (answered, judge) | {Score(run.GroundednessMean)} (n = {run.Questions.Count(q => !q.Abstained)}) |");
        b.AppendLine(CultureInfo.InvariantCulture, $"| Relevance, mean 1–5 (answered, judge) | {Score(run.RelevanceMean)} (n = {run.Questions.Count(q => !q.Abstained)}) |");
        b.AppendLine(CultureInfo.InvariantCulture, $"| Judge failures | {run.JudgeFailures} |");
        foreach (var check in handChecks.Where(c => SameSecond(c.AnswerRunStartedUtc, run.Info.StartedUtc)))
        {
            b.AppendLine(CultureInfo.InvariantCulture, $"| {check.Metric} | {check.Value} |");
        }

        b.AppendLine(CultureInfo.InvariantCulture, $"| Tokens (answers) | {run.InputTokens:N0} in / {run.OutputTokens:N0} out |");
        // Runs before the metadata-key fix recorded no judge tokens; say so rather than print 0 (spec 0004 §9).
        var judgeRecorded = run.JudgeInputTokens > 0 || run.Questions.All(q => q.Judgements.Count == 0);
        if (judgeRecorded)
        {
            b.AppendLine(CultureInfo.InvariantCulture, $"| Tokens (judge) | {run.JudgeInputTokens:N0} in / {run.JudgeOutputTokens:N0} out |");
            b.AppendLine(CultureInfo.InvariantCulture, $"| Cost at list price | ${Metrics.Format(run.CostUsd, 3)} |");
        }
        else
        {
            b.AppendLine("| Tokens (judge) | not recorded in this run |");
            b.AppendLine(CultureInfo.InvariantCulture, $"| Cost at list price | ${Metrics.Format(run.CostUsd, 3)} for the answers; judge not recorded |");
        }

        b.AppendLine(CultureInfo.InvariantCulture, $"| p50 latency, model-calling answers | {run.LatencyP50Ms / 1000:F1} s |").AppendLine();
    }

    private static List<HandCheck> LoadHandChecks()
    {
        if (!File.Exists(HandChecksFile))
        {
            return [];
        }

        using var document = JsonDocument.Parse(File.ReadAllText(HandChecksFile));
        return document.RootElement.GetProperty("checks").Deserialize<List<HandCheck>>(Json) ?? [];
    }

    private static bool SameSecond(DateTimeOffset a, DateTimeOffset b) =>
        a.ToUnixTimeSeconds() == b.ToUnixTimeSeconds();

    private static List<string> Stages(IEnumerable<RunInfo> infos) =>
        [.. infos.GroupBy(Stage).OrderBy(g => g.Min(i => i.StartedUtc)).Select(g => g.Key)];

    private static List<T> Latest<T>(IEnumerable<T> runs, Func<T, RunInfo> info)
    {
        var all = runs.ToList();
        var stageStarted = all.GroupBy(r => Stage(info(r))).ToDictionary(g => g.Key, g => g.Min(r => info(r).StartedUtc));
        return
        [
            .. all.GroupBy(r => (Stage(info(r)), info(r).Config)).Select(g => g.MaxBy(r => info(r).StartedUtc)!)
                .OrderBy(r => stageStarted[Stage(info(r))])
                .ThenBy(r => EvalConfiguration.All.ToList().FindIndex(c => c.Name == info(r).Config)),
        ];
    }

    private static string Score(double? value) => value is null ? "–" : Metrics.Format(value.Value, 2);
}
